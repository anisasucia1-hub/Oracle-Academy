public class GabungString {
    public static void main(String[] args) {
        // Mendeklarasikan dan menginstansiasi dua object String terpisah
        String bagianPertama = "Oracle ";
        String bagianKedua = "Academy";

        // Menggabungkan keduanya dan menetapkan ke object String ketiga
        String hasilGabungan = bagianPertama + bagianKedua;

        // Menampilkan hasil ke layar
        System.out.println("Hasil gabungan: " + hasilGabungan);
    }
}